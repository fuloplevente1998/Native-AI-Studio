package com.example.ui.theme

import androidx.compose.ui.graphics.Color
import com.example.model.AppLanguage

enum class PaletteCategory {
    ALL,
    BASIC,
    VIVID
}

data class TrainPilotPalette(
    val id: Int,
    val key: String,
    val nameHu: String,
    val nameEn: String,
    val nameDe: String,
    val nameRo: String,
    val category: PaletteCategory,
    val background: Color,
    val surface: Color,
    val surfaceElevated: Color,
    val primary: Color,
    val onPrimary: Color,
    val secondary: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val cardBorder: Color,
    val success: Color = Color(0xFF34D399),
    val warning: Color = Color(0xFFFBBF24),
    val danger: Color = Color(0xFFF87171),
    val isDark: Boolean = true,
    val primaryBright: Color = primary,
    val tertiary: Color = secondary,
    val sleepAccent: Color = if (isDark) Color(0xFF818CF8) else Color(0xFF4F46E5),
    val heartAccent: Color = if (isDark) Color(0xFFFB7185) else Color(0xFFE11D48),
    val stepsAccent: Color = if (isDark) Color(0xFF34D399) else Color(0xFF059669),
    val energyAccent: Color = if (isDark) Color(0xFFFBBF24) else Color(0xFFD97706)
) {
    // Aliases for screen compatibility & WCAG AA contrast compliance (>= 4.5:1 on surface & surfaceElevated)
    val surfaceCard: Color get() = surface
    val textMuted: Color = textSecondary.copy(alpha = 0.90f)

    fun localizedName(lang: AppLanguage): String = when (lang) {
        AppLanguage.HU -> nameHu
        AppLanguage.EN -> nameEn
        AppLanguage.DE -> nameDe
        AppLanguage.RO -> nameRo
    }

    fun localizedName(langCode: String): String = when (langCode.uppercase()) {
        "HU" -> nameHu
        "EN" -> nameEn
        "DE" -> nameDe
        "RO" -> nameRo
        else -> nameHu
    }
}

